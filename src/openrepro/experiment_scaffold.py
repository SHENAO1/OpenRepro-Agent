from __future__ import annotations

from pathlib import Path
from typing import Any

from .approval import load_verified_candidates
from .experiment_inputs import write_experiment_inputs
from .experiment_spec import write_experiment_spec
from .experiment_templates import TEMPLATE_SCHEMA_VERSION, normalize_template, template_expected_artifacts
from .utils import iso_now, local_timestamp_for_path, read_json, safe_write_text, slugify, write_json

SCAFFOLD_SCHEMA_VERSION = "0.9.0"


def _load_candidates(project_dir: Path, filename: str) -> list[dict[str, Any]]:
    data = read_json(project_dir / "workspace" / filename, default={}) or {}
    if not isinstance(data, dict):
        return []
    candidates = data.get("candidates", [])
    return candidates if isinstance(candidates, list) else []


def _basic_runner_stub(ready_message: str, runnable: bool) -> str:
    if runnable:
        runner_main = f'''def main() -> None:
    print("{ready_message}")
    print("Domain-specific experiment code has not been implemented yet.")
'''
    else:
        runner_main = '''def main() -> None:
    raise SystemExit(
        "This experiment scaffold requires human verification before execution."
    )
'''

    return f'''"""Experiment runner stub generated by OpenRepro-Agent.

Fill this in only after candidate formulas and parameters have been reviewed.
"""

from __future__ import annotations


{runner_main}


if __name__ == "__main__":
    main()
'''


def _boc_like_runner(ready_message: str) -> str:
    return '''"""BOC-like experiment template generated by OpenRepro-Agent."""

from __future__ import annotations

import csv
import json
import math
import os
import random
from pathlib import Path

READY_MESSAGE = ''' + repr(ready_message) + '''


def _load_inputs() -> dict:
    inputs_path = Path(os.environ.get("OPENREPRO_EXPERIMENT_INPUTS", "experiment_inputs.json"))
    if not inputs_path.exists():
        return {}
    return json.loads(inputs_path.read_text(encoding="utf-8"))


def _number(params: dict, name: str, default: float) -> float:
    value = params.get(name, default)
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def main() -> None:
    print(READY_MESSAGE)
    run_dir = Path(os.environ["OPENREPRO_RUN_DIR"])
    data_dir = run_dir / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    inputs = _load_inputs()
    params = inputs.get("parameter_values", {})

    seed = int(_number(params, "seed", 7))
    code_length = int(_number(params, "code_length", 128))
    noise_std = _number(params, "noise_std", 0.05)
    random.seed(seed)

    rows = []
    correlation = 0.0
    energy = 0.0
    for index in range(code_length):
        code_chip = random.choice([-1, 1])
        signal = math.sin(2.0 * math.pi * index / 16.0)
        observed = code_chip * signal + random.gauss(0.0, noise_std)
        product = observed * code_chip
        correlation += product
        energy += observed * observed
        rows.append(
            {
                "index": index,
                "code_chip": code_chip,
                "signal": signal,
                "observed": observed,
                "correlation_term": product,
            }
        )

    metrics = {
        "template": "boc-like",
        "seed": seed,
        "code_length": code_length,
        "noise_std": noise_std,
        "mean_correlation": correlation / code_length,
        "signal_energy": energy,
        "input_completeness": inputs.get("input_completeness", {}),
    }
    (data_dir / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\\n", encoding="utf-8")

    with (data_dir / "boc_trace.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    print("Wrote template artifacts: data/metrics.json, data/boc_trace.csv")


if __name__ == "__main__":
    main()
'''


def _numeric_sweep_runner(ready_message: str) -> str:
    return '''"""Numeric sweep experiment template generated by OpenRepro-Agent."""

from __future__ import annotations

import csv
import json
import os
from pathlib import Path

READY_MESSAGE = ''' + repr(ready_message) + '''


def _load_inputs() -> dict:
    inputs_path = Path(os.environ.get("OPENREPRO_EXPERIMENT_INPUTS", "experiment_inputs.json"))
    if not inputs_path.exists():
        return {}
    return json.loads(inputs_path.read_text(encoding="utf-8"))


def _noise_values(params: dict) -> list[float]:
    values = params.get("noise_std_values")
    if isinstance(values, list) and values:
        return [float(value) for value in values]
    if params.get("noise_std") is not None:
        value = float(params["noise_std"])
        return sorted({0.0, value, value * 2.0})
    return [0.0, 0.05, 0.1, 0.2]


def main() -> None:
    print(READY_MESSAGE)
    run_dir = Path(os.environ["OPENREPRO_RUN_DIR"])
    data_dir = run_dir / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    inputs = _load_inputs()
    params = inputs.get("parameter_values", {})

    noise_values = _noise_values(params)
    rows = []
    for index, noise_std in enumerate(noise_values):
        score = 1.0 / (1.0 + noise_std * 10.0)
        rows.append(
            {
                "index": index,
                "noise_std": noise_std,
                "stability_score": score,
            }
        )

    best = max(rows, key=lambda item: item["stability_score"])
    metrics = {
        "template": "numeric-sweep",
        "sweep_count": len(rows),
        "best_noise_std": best["noise_std"],
        "best_stability_score": best["stability_score"],
        "input_completeness": inputs.get("input_completeness", {}),
    }
    (data_dir / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\\n", encoding="utf-8")

    with (data_dir / "sweep.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

    print("Wrote template artifacts: data/metrics.json, data/sweep.csv")


if __name__ == "__main__":
    main()
'''


def _template_runner(template: str, ready_message: str) -> str | None:
    if template == "boc-like":
        return _boc_like_runner(ready_message)
    if template == "numeric-sweep":
        return _numeric_sweep_runner(ready_message)
    return None


def scaffold_experiment(
    project_dir: Path,
    experiment_id: str | None = None,
    acknowledge_candidates: bool = False,
    template: str = "basic",
) -> dict[str, Any]:
    """Create a guarded experiment scaffold from candidate ledger artifacts."""
    project_dir = Path(project_dir)
    if not project_dir.exists():
        raise FileNotFoundError(f"Project directory not found: {project_dir}")
    template_name = normalize_template(template)

    formula_candidates = _load_candidates(project_dir, "formula_candidates.json")
    parameter_candidates = _load_candidates(project_dir, "parameter_candidates.json")
    model_ledger = read_json(project_dir / "workspace" / "model_ledger.json", default={}) or {}
    verified = load_verified_candidates(project_dir)
    verified_formula_ids = [str(item) for item in verified.get("formula_candidate_ids", [])]
    verified_parameter_ids = [str(item) for item in verified.get("parameter_candidate_ids", [])]
    has_verified_inputs = bool(verified_formula_ids or verified_parameter_ids)

    exp_id = slugify(experiment_id or f"exp_{local_timestamp_for_path()}")
    exp_dir = project_dir / "experiments" / exp_id
    exp_dir.mkdir(parents=True, exist_ok=False)

    if has_verified_inputs:
        status = "verified_inputs_ready"
        runnable = True
    elif acknowledge_candidates:
        status = "candidate_inputs_acknowledged"
        runnable = True
    else:
        status = "approval_required"
        runnable = False
    config = {
        "schema_version": SCAFFOLD_SCHEMA_VERSION,
        "experiment_id": exp_id,
        "created_at": iso_now(),
        "status": status,
        "runnable": runnable,
        "template": template_name,
        "policy": "Generated from candidate evidence only; human verification is required before scientific use.",
        "source_files": [source.get("source_name") for source in (model_ledger.get("sources") or [])],
        "formula_candidate_ids": [item.get("candidate_id") for item in formula_candidates],
        "parameter_candidate_ids": [item.get("candidate_id") for item in parameter_candidates],
        "verified_candidates_path": "workspace/verified_candidates.json" if has_verified_inputs else None,
        "verified_formula_candidate_ids": verified_formula_ids,
        "verified_parameter_candidate_ids": verified_parameter_ids,
        "candidate_status": "candidate_unverified",
    }
    write_json(exp_dir / "experiment_config.json", config)
    experiment_inputs = write_experiment_inputs(project_dir, exp_id, exp_dir, template_name)
    expected = template_expected_artifacts(template_name)
    write_json(
        exp_dir / "expected_artifacts.json",
        {
            "schema_version": TEMPLATE_SCHEMA_VERSION,
            "experiment_id": exp_id,
            "template": template_name,
            "required": expected["required"],
            "optional": expected["optional"],
        },
    )
    experiment_spec = write_experiment_spec(project_dir, exp_id, exp_dir)
    safe_write_text(
        exp_dir / "README.md",
        f"""# Experiment Scaffold: {exp_id}

This scaffold was generated by OpenRepro-Agent v1.26.0 from candidate formulas,
parameters, and model ledger entries.

## Status

- status: {status}
- runnable: {runnable}
- template: {template_name}
- formula candidates: {len(formula_candidates)}
- parameter candidates: {len(parameter_candidates)}
- verified formula candidates: {len(verified_formula_ids)}
- verified parameter candidates: {len(verified_parameter_ids)}
- input completeness: {experiment_inputs['input_completeness']['status']}

## Guardrail

All formulas and parameters are `candidate_unverified` until a human checks them
against the paper. This scaffold is a coding starting point, not a reproduction
claim.

When `verified_candidates_path` is present in `experiment_config.json`, the
listed candidates have been promoted by a human reviewer for implementation
work. That approval still does not claim scientific reproduction success.

## Expected Artifacts

`run-experiment` reads `expected_artifacts.json` and includes these required
paths in the run manifest. Template-specific runners should write their outputs
under the directory named by the `OPENREPRO_RUN_DIR` environment variable.

## Experiment Inputs

Verified candidates are mapped into `experiment_inputs.json`. Template runners
read that file through the `OPENREPRO_EXPERIMENT_INPUTS` environment variable.
""",
    )
    safe_write_text(
        exp_dir / "APPROVAL_REQUIRED.md",
        """# Approval Required

Before running or extending this experiment:

1. Verify formula candidates against the paper.
2. Verify parameter candidates and units.
3. Record accepted assumptions in `experiment_config.json`.
4. Keep outputs tied to manifests and reports.

Do not report this scaffold as a paper reproduction result.
""",
    )
    if runnable:
        ready_message = (
            "Verified candidate scaffold is ready for implementation work."
            if has_verified_inputs
            else "Candidate inputs were acknowledged for implementation work."
        )
    else:
        ready_message = "Human verification is required before execution."

    safe_write_text(
        exp_dir / "runner_stub.py",
        _basic_runner_stub(ready_message, runnable),
    )
    runner_code = _template_runner(template_name, ready_message)
    if runnable and runner_code is not None:
        safe_write_text(exp_dir / "runner.py", runner_code)

    summary = {
        "schema_version": SCAFFOLD_SCHEMA_VERSION,
        "created_at": iso_now(),
        "experiment_id": exp_id,
        "experiment_dir": str(exp_dir),
        "status": status,
        "runnable": runnable,
        "template": template_name,
        "required_artifact_count": len(expected["required"]),
        "optional_artifact_count": len(expected["optional"]),
        "experiment_inputs_path": str(exp_dir / "experiment_inputs.json"),
        "experiment_spec_path": str(exp_dir / "experiment_spec.json"),
        "experiment_spec_schema_version": experiment_spec["schema_version"],
        "input_completeness_status": experiment_inputs["input_completeness"]["status"],
        "missing_required_inputs": experiment_inputs["input_completeness"]["missing"],
        "formula_candidate_count": len(formula_candidates),
        "parameter_candidate_count": len(parameter_candidates),
        "verified_formula_candidate_count": len(verified_formula_ids),
        "verified_parameter_candidate_count": len(verified_parameter_ids),
        "next_step": f"Review {exp_dir / 'APPROVAL_REQUIRED.md'} and verify candidates before implementation.",
    }
    write_json(project_dir / "workspace" / "experiment_scaffold_summary.json", summary)
    return summary
